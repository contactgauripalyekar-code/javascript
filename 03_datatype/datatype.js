// Premitive Data types :

// number - 123
// bigint
// string - "gauri"
// boolean - true/ false
// null - standalone value  eg: the temperature machine is not working properly the value should be set to null and not 0 
// undefined ---> variable is defined but value is not assigned 
// symbol 

// Non Premitive Data Type : 

// object 

// typeof - is used to know the type 

console.log(typeof "gauri");   // string 
console.log(typeof 6);     // number
console.log(typeof null);     // object
console.log(typeof undefined);      // undefined
